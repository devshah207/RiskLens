"""Unified maintained command-line interface for RiskLens research workflows.

Thin orchestration only: all modeling and data protections stay in tested libraries.
Legacy module CLIs remain available for backward compatibility during migration.
"""

from __future__ import annotations

import argparse
from pathlib import Path


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="risklens", description="RiskLens development-only research workflows"
    )
    sub = p.add_subparsers(dest="command", required=True)

    compare = sub.add_parser(
        "compare", help="Run chronological 9-vs-11-feature XGBoost comparison"
    )
    compare.add_argument("nifty_csv")
    compare.add_argument("external_csv")
    compare.add_argument(
        "--output-dir", default="data/processed/multifactor_comparison"
    )
    compare.add_argument("--overwrite", action="store_true")

    demo = sub.add_parser(
        "demo", help="Generate XGBoost, VaR, LSTM and offline dashboard"
    )
    demo.add_argument("--nifty", default="data/processed/multiyear/nifty50_ohlc.csv")
    demo.add_argument(
        "--external", default="data/processed/external/nifty50_external_development.csv"
    )
    demo.add_argument(
        "--reference-dir", default="data/processed/multifactor_comparison"
    )
    demo.add_argument("--output-dir", default="data/processed/citi_validation")
    demo.add_argument(
        "--overwrite",
        action="store_true",
        help="Replace outputs previously generated by this workflow",
    )

    tune = sub.add_parser(
        "tune", help="Resume Optuna XGBoost and Apple-MPS LSTM searches"
    )
    tune.add_argument("nifty_csv")
    tune.add_argument("external_csv")
    tune.add_argument("--output-dir", required=True)
    tune.add_argument("--xgb-trials", type=int, default=0)
    tune.add_argument("--lstm-trials", type=int, default=0)
    tune.add_argument("--device", choices=("auto", "mps", "cpu"), default="auto")
    frozen = sub.add_parser(
        "evaluate-frozen", help="Frozen XGBoost vs verified Optuna LSTM trial #86"
    )
    frozen.add_argument("--nifty", default="data/processed/multiyear/nifty50_ohlc.csv")
    frozen.add_argument(
        "--external", default="data/processed/external/nifty50_external_development.csv"
    )
    frozen.add_argument(
        "--study-db", default="data/processed/optuna_search/optuna_studies.sqlite3"
    )
    frozen.add_argument("--device", choices=("auto", "cpu", "mps"), default="auto")
    frozen.add_argument("--output-dir", default="data/processed/phase4_validation")
    frozen.add_argument("--overwrite", action="store_true")
    validation = sub.add_parser(
        "validate-risk",
        help="Phase 5 development-only validation of frozen predictions and historical VaR",
    )
    validation.add_argument(
        "--predictions",
        default="data/processed/phase4_validation/frozen_model_predictions.csv",
    )
    validation.add_argument(
        "--var-backtest",
        default="data/processed/citi_validation/historical_var_backtest.csv",
    )
    validation.add_argument("--output-dir", default="data/processed/phase5_validation")
    validation.add_argument("--bootstrap-samples", type=int, default=1000)
    validation.add_argument("--block-length", type=int, default=10)
    validation.add_argument("--overwrite", action="store_true")
    holdout = sub.add_parser(
        "evaluate-holdout",
        help="ONE-TIME locked 2025–2026 out-of-time evaluation (explicit unlock required)",
    )
    holdout.add_argument(
        "--nifty", default="data/processed/multiyear/nifty50_ohlc.csv"
    )
    holdout.add_argument(
        "--development-external",
        default="data/processed/external/nifty50_external_development.csv",
    )
    holdout.add_argument("--vix", required=True, help="VIX OHLC source with Dec 2024 context through Sep 2026")
    holdout.add_argument("--sp500", required=True, help="S&P 500 OHLC with Dec 2024 context through Sep 2026")
    holdout.add_argument(
        "--study-db", default="data/processed/optuna_search/optuna_studies.sqlite3"
    )
    holdout.add_argument("--device", choices=("auto", "cpu", "mps"), default="auto")
    holdout.add_argument("--output-dir", default="data/processed/phase5_final_holdout")
    holdout.add_argument("--confirm-locked-protocol", action="store_true")
    return p


def run(args: argparse.Namespace) -> int:
    if args.command == "evaluate-holdout":
        from risklens.evaluation.final_holdout import save_holdout

        report = save_holdout(
            args.nifty,
            args.development_external,
            args.vix,
            args.sp500,
            args.study_db,
            args.output_dir,
            device=args.device,
            confirm_locked_protocol=args.confirm_locked_protocol,
        )
        print(
            "ONE-TIME OUT-OF-TIME HOLDOUT RECORDED:",
            report["eligible_holdout_rows"],
            "eligible forecast dates; preselected model frozen",
        )
        print("Verdict:", Path(args.output_dir) / "final_holdout_verdict.md")
        return 0

    if args.command == "validate-risk":
        from risklens.evaluation.risk_validation import save_risk_validation

        report = save_risk_validation(
            args.predictions,
            args.var_backtest,
            args.output_dir,
            overwrite=args.overwrite,
            n_resamples=args.bootstrap_samples,
            block_length=args.block_length,
        )
        print(
            "PASS: development diagnostics,",
            report["observations"],
            "aligned observations; 2025+ holdout sealed",
        )
        print("Report:", Path(args.output_dir) / "risk_validation_report.md")
        return 0

    if args.command == "evaluate-frozen":
        from risklens.models.frozen_comparison import save_frozen_comparison

        report = save_frozen_comparison(
            args.nifty,
            args.external,
            args.output_dir,
            study_db=args.study_db,
            device=args.device,
            overwrite=args.overwrite,
        )
        print("PASS: fixed XGBoost versus Optuna LSTM trial #86; 2025+ sealed")
        for period, result in report["period_scores"].items():
            print(f"{period}: {result['rows']} observations")
            for model, scores in result["metrics"].items():
                print(f"  {model}: Brier={scores['brier_score']:.6f}, "
                      f"ROC-AUC={scores['roc_auc']}")
        print("Report:", Path(args.output_dir) / "frozen_model_report.md")
        return 0

    if args.command == "compare":
        from risklens.models.multifactor_comparison import save_multifactor_comparison

        report = save_multifactor_comparison(
            args.nifty_csv, args.external_csv, args.output_dir, overwrite=args.overwrite
        )
        print(
            f"XGBoost comparison: {report['total_validation_rows']} development observations"
        )
        return 0

    if args.command == "tune":
        if (
            args.xgb_trials < 0
            or args.lstm_trials < 0
            or not (args.xgb_trials or args.lstm_trials)
        ):
            raise ValueError(
                "Choose at least one positive trial count; negative trial counts are invalid"
            )
        from risklens.models.optuna_research import optimize

        optimize(
            args.nifty_csv,
            args.external_csv,
            args.output_dir,
            xgb_trials=args.xgb_trials,
            lstm_trials=args.lstm_trials,
            device=args.device,
        )
        return 0

    if args.command == "demo":
        from risklens.models.multifactor_comparison import save_multifactor_comparison
        from risklens.models.market_risk_monitor import save_var_backtest
        from risklens.models.sequence_lstm import save_sequence_benchmark

        nifty, ext = Path(args.nifty), Path(args.external)
        for path in (nifty, ext):
            if not path.is_file():
                raise FileNotFoundError(f"Required input not found: {path}")
        ref_dir = Path(args.reference_dir)
        ref = ref_dir / "multifactor_comparison_predictions.csv"
        if not ref.exists():
            print("Generating missing XGBoost reference (development only)")
            save_multifactor_comparison(nifty, ext, ref_dir, overwrite=False)
        out = Path(args.output_dir)
        out.mkdir(parents=True, exist_ok=True)
        save_var_backtest(nifty, ref, out, overwrite=args.overwrite)
        report = save_sequence_benchmark(
            nifty,
            ext,
            ref,
            out,
            overwrite=args.overwrite,
            var_report_path=out / "historical_var_report.json",
        )
        print(
            f"PASS: {report['n_validation_predictions']} development predictions; 2025+ sealed"
        )
        print("Dashboard:", out / "risk_model_validation_dashboard.html")
        return 0
    raise ValueError(f"Unknown command: {args.command}")


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        return run(args)
    except (ValueError, FileNotFoundError, OSError) as exc:
        parser.exit(2, f"RiskLens failed: {exc}\n")


if __name__ == "__main__":
    raise SystemExit(main())
